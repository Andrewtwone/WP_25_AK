package OrderWithoutStateDemo;

public class Ansi {

    public static final String RESET = "\u001B[0m";

    public static final String BLUE = "\u001B[34m";    // action
    public static final String CYAN = "\u001B[36m";    // state
    public static final String GREEN = "\u001B[32m";   // success
    public static final String YELLOW = "\u001B[33m";  // info
    public static final String RED = "\u001B[31m";     // error
}
